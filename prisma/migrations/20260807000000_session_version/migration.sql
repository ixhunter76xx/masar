-- ═══ إبطال الجلسات عند تغيير كلمة المرور ════════════════════════════
--
-- الجلسة في مسار رمز JWT موقَّع، لا صفٌّ في القاعدة. فلا سبيل لإنهائها
-- من الخادم: إعادة تعيين كلمة المرور تغيّر التجزئة ولا تمسّ رمزًا
-- أُصدر قبلها، فمن يملك جلسةً مسروقة يبقى داخلها بعد إعادة التعيين.
--
-- العمود رقم إصدار: الرمز يحمل قيمته وقت الدخول، ويُقارَن بها في كل
-- طلب (`getLiveUser`). رفعُه بمقدار واحد يُبطل كل الجلسات المفتوحة
-- لهذا الحساب دفعةً واحدة — وهو أيضًا ما يلزم لزرّ «إنهاء الجلسات»
-- إن أُضيف لاحقًا.
--
-- **إضافي بالكامل**: عمود واحد بقيمة افتراضية. الصفوف القائمة تأخذ 0،
-- والرموز الحالية لا تحمل الرقم فتُعامَل معاملة 0 أيضًا، فلا تنتهي
-- جلسة أحد بتطبيق هذه الهجرة.
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE "users" ADD COLUMN "sessionVersion" INTEGER NOT NULL DEFAULT 0;
