-- رقم واتساب بصيغة دولية بلا رموز (97333060460) — قناة إتمام الدفع
-- اليدوي. اختياري لأن حسابات الإدارة والأساتذة القائمة لا تملكه.
ALTER TABLE "users" ADD COLUMN "phone" TEXT;

-- تسلسل رقم الطلب المقروء (MSR-2026-0001).
-- لا يُصفَّر مع السنة عمدًا: رقمٌ فريد أبدًا أهمّ من رقمٍ جميل، والتصفير
-- السنوي يحتاج مهمة مجدولة تُنسى فتصطدم الأرقام في أول يناير.
--
-- تسلسل لا COUNT(*): العدّ يتسابق تحت طلبين متزامنين فيولّد الرقم
-- نفسه مرتين. يُقرأ في requestProductOrder عبر nextval().
CREATE SEQUENCE "order_number_seq" AS BIGINT START 1;

-- أثر المراجعة البشرية للقناة اليدوية؛ تبقى فارغة في الدفع الآلي.
-- نقل مالٍ بموافقة إنسان بلا تسجيل مَن وافق ومتى هو ما يؤلم بعد أشهر
-- عند أول نزاع، لا اليوم.
ALTER TABLE "payments"
  ADD COLUMN "reviewedById" TEXT REFERENCES "users"(id) ON DELETE SET NULL,
  ADD COLUMN "reviewedAt" TIMESTAMP(3),
  ADD COLUMN "reviewNote" TEXT;
