-- ═══ الدرس يوجد قبل فيديوه ══════════════════════════════════════════
--
-- كان `objectKey` إلزاميًا، فلم يكن الدرس قادرًا على الوجود بلا ملف.
-- ونتيجة ذلك أن السبيل الوحيد لإنشاء درس هو رفع فيديو فعلي — فلا
-- يستطيع المدرّس تخطيط منهج المقرر (العناوين والترتيب وأيّها معاينة
-- مجانية) قبل أن يصوّر كل شيء.
--
-- `NULL` يعني الآن «مخطَّط، بانتظار الرفع». والفهرس الفريد يبقى صالحًا
-- لأن Postgres لا يعدّ `NULL` تكرارًا.
--
-- ── ولماذا تُفرَّغ مفاتيح البذرة ────────────────────────────────────
-- الدروس الأربعة المزروعة تحمل `seed/ARAB110/1..4` ولا كائن لها في R2
-- إطلاقًا. وبقاؤها بمفتاح وهمي كان يجعلها **عاجزة عن أن تصير READY
-- أبدًا**: الرفع كان يُنشئ صفًّا جديدًا بجانبها لا يملؤها. تفريغُها
-- يحوّلها إلى ما هي عليه فعلًا — دروس مخطَّطة — فتصير قابلة للرفع.
--
-- شرط `LIKE 'seed/%'` يقصر التغيير على المفاتيح الوهمية وحدها؛ أي
-- مفتاح حقيقي يقابله كائن يبقى كما هو.
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE "course_materials" ALTER COLUMN "objectKey" DROP NOT NULL;

UPDATE "course_materials"
SET "objectKey" = NULL
WHERE "objectKey" LIKE 'seed/%' AND "status" = 'PENDING';
