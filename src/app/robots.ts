import type { MetadataRoute } from "next";

import { SITE } from "@/lib/site";

/**
 * الفهرسة: الكتالوج مفتوح، وما خلف الدخول ممنوع.
 *
 * ── ⚠ ما كان هنا، ولماذا لم يعد صحيحًا ──────────────────────────────
 * كان `disallow: "/"` — منعًا كاملًا، وتعليلُه: «كل صفحاتها خلف تسجيل
 * دخول، ولا يوجد محتوى عام». وكان ذلك صحيحًا يوم كُتب. ثم بُنيت طبقة
 * السوق: `/courses` و`/courses/[slug]` يستجيبان **٢٠٠ لزائرٍ مجهول**
 * ويعرضان الأسعار والباقات والمعاينة المجانية. فبقي المنع يمنع
 * الفهرسة عن الصفحات التي وُجدت لتُوجَد.
 *
 * ── والحدّ بين المسموح والممنوع هو حدّ الوصول نفسه ───────────────────
 * المسموح: الكتالوج وصفحات المقررات والصفحتان القانونيتان — وكلها
 * عامّة بقرارٍ صريح. والممنوع: كل ما يحتاج جلسة. وهذا ليس حمايةً —
 * `robots.txt` توجيهٌ يحترمه الزاحف المهذّب وحده — بل تنظيفٌ لما
 * يُعرض في البحث. الحماية تبقى في `middleware` وفحص الجلسة.
 *
 * ── ولماذا `/login` و`/signup` ممنوعتان مع أنهما عامّتان ────────────
 * لا تفيدان باحثًا: من يبحث عن مقرر يريد المقرر لا نموذج دخول.
 * وظهورهما يضيف ضجيجًا يزاحم الصفحات التي تبيع.
 *
 * ⚠ وهذا **قرار مالك** لا تفصيل تقنيّ: عكسُه سطرٌ واحد
 * (`allow` → `disallow: "/"`) إن أُريد إطلاقٌ هادئ لا يظهر في البحث.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: "*",
        allow: ["/courses", "/legal"],
        disallow: [
          "/dashboard",
          "/learn",
          "/grades",
          "/messages",
          "/orders",
          "/profile",
          "/settings",
          "/login",
          "/signup",
          "/forgot-password",
          "/api/",
        ],
      },
    ],
    sitemap: `${SITE.url}/sitemap.xml`,
    host: SITE.url,
  };
}
