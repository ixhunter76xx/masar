import type { Metadata } from "next";

import { AdminTabs } from "@/components/admin/AdminTabs";
import { AppPage } from "@/components/shell/AppPage";
import { requireAdmin } from "@/lib/data/admin";

export const metadata: Metadata = { title: "الإدارة" };

/**
 * تخطيط أقسام الإدارة: شريط التبويبات ثابت، والمحتوى وحده يتبدّل تحته.
 *
 * ── ⚠ العلّة التي وُجد لها — بلاغُ المالك ────────────────────────────
 * «عندما أبدّل بين الطلبات والمقررات يختفي المحتوى كاملًا، والخطّ
 * المتحرّك لا يعمل بالشكل المطلوب.» وكان محقًّا، والسبب بنيويّ:
 *
 * لم يكن لهذا المسار تخطيطٌ أصلًا. كانت **كل صفحةٍ تصيّر `AdminTabs`
 * بنفسها** داخل `AppPage` الخاص بها. فالتنقّل بين تبويبين يفكّك
 * الصفحة كلَّها ومعها شريطُ التبويبات، ويحلّ محلّها `loading.tsx`
 * الذي يرسم هيكل **المحتوى** ولا يرسم شريطًا. فيغيب الشريط والمحتوى
 * معًا — مقيسٌ في المتصفّح: `tabs: 0` طوال ‏٨٧٥ms قبل هذا الإصلاح.
 *
 * وللسبب نفسه كان المؤشّر المنزلق لا يستطيع أن ينزلق: `layoutId`
 * يصل بين موضعين لعنصرٍ **باقٍ**، وهذا كان يُفكَّك ويُبنى من جديد.
 *
 * ── والعلاج هو بنية تبويبات المقرر نفسها ───────────────────────────
 * `learn/[courseId]/(tabs)` حلّ هذا من قبل: التخطيط يحمل الرأس
 * والتبويبات، والصفحات تحته أجزاءٌ عارية. فالتبويبات لا تُفكَّك،
 * و`loading.tsx` مسؤوليتُه المحتوى وحده. وهو ما طلبه المالك حرفيًّا:
 * «من المفترض أن يكون مثل الذي فعلناه في مقرراتي».
 *
 * ── وحدّ المجموعة `(tabs)` مقصود ────────────────────────────────────
 * صفحتا التفصيل — `courses/[courseId]` و`students/[userId]` — بقيتا
 * **خارجها** عمدًا: لكلٍّ منهما رأسها وسياقها، ولا تنتميان إلى شريط
 * التبويبات. وهي القاعدة نفسها التي يسجّلها CLAUDE.md عن
 * `learn/[courseId]/`: ما يعيش داخل `(tabs)` لا يصيّر `AppPage`،
 * وما يعيش خارجها يصيّره بنفسه.
 *
 * ── والحارس هنا لا يُغني عنه حارسُ الصفحة ──────────────────────────
 * `requireAdmin()` مكرَّرٌ في كل صفحةٍ تحته عمدًا. App Router قد
 * يصيّر التخطيط والصفحة **بالتوازي**، فلا يضمن أحدهما الآخر — وهو
 * فخٌّ مسجَّل في `PORT-HANDOFF.md` كلّف استثناءً في سجلّ الخادم.
 * والتكرار بلا ثمن: `getLiveUser` مغلَّفٌ بـ`cache()` فالاستعلام
 * واحدٌ لكل طلب مهما تعدّد المستدعون.
 */
export default async function SettingsTabsLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  await requireAdmin();

  return (
    <AppPage title="الإدارة" hidePageHeader>
      <AdminTabs />
      {children}
    </AppPage>
  );
}
