import "server-only";

/**
 * ═══ الإبلاغ عن الأخطاء ══════════════════════════════════════════════
 *
 * ── لماذا وسيط بدل `console.error` مباشرة ───────────────────────────
 * المنصة تعمل بلا خادم دائم: `console.error` يذهب إلى سجلّ الدالة عند
 * المستضيف، وهو موجود لكن لا أحد يقرؤه ولا شيء ينبّه عليه. وحين
 * يُوصَل مرصد أخطاء حقيقي، لا نريد أن نبحث عن كل موضع طباعة في
 * المستودع ونعدّله — بل موضعًا واحدًا.
 *
 * ── لماذا لا Sentry الآن ────────────────────────────────────────────
 * يحتاج حسابًا و`DSN` لا يملكهما المستودع. فبدل تعليق «TODO أضف
 * Sentry»، هذه الدالة تعمل اليوم فعلًا (سجلّ منظَّم قابل للبحث)
 * وتصير غدًا نقطة الوصل الوحيدة: تُضاف فيها ثلاثة أسطر ويُنشر.
 *
 * ── ما الذي تحرسه ───────────────────────────────────────────────────
 * أُنشئت لأن `markOrderPaid` كانت تبتلع كل فشل في رسالة واحدة بلا
 * أثر — على مسار مال بلا بوابة، أي أن السجلّ الوحيد كان محادثة
 * واتساب. لا تُستعمل للأخطاء المتوقّعة (بيانات غير صالحة، صلاحية
 * مرفوضة): تلك إجابات لا أعطال، وإغراق المرصد بها يجعله بلا فائدة.
 * ═══════════════════════════════════════════════════════════════════
 */

export type ErrorContext = Record<string, unknown>;

/**
 * يُبلّغ عن خطأ غير متوقّع.
 *
 * `scope` وسم قصير ثابت يُبحث به — اسم الدالة أو المسار، لا رسالة
 * حرّة تتغيّر مع كل تعديل فتكسر أي تجميع.
 */
export function reportError(
  scope: string,
  error: unknown,
  context: ErrorContext = {},
): void {
  const normalised =
    error instanceof Error
      ? { name: error.name, message: error.message, stack: error.stack }
      : { name: "NonError", message: String(error), stack: undefined };

  /* سطر واحد منظَّم: المستضيف يقصّ السطور الطويلة ويفصل المتعددة،
     فيضيع نصف الأثر حين يُقرأ. */
  console.error(
    JSON.stringify({
      level: "error",
      scope,
      at: new Date().toISOString(),
      error: normalised,
      ...context,
    }),
  );

  /*
   * نقطة الوصل بمرصد خارجي — تُملأ حين يوجد DSN، ولا يتغيّر معها أي
   * مستدعٍ:
   *
   *   if (process.env.SENTRY_DSN) Sentry.captureException(error, {
   *     tags: { scope }, extra: context,
   *   });
   */
}
