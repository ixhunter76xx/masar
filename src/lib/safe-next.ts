/**
 * تطهير وجهة ما بعد الدخول.
 *
 * ── ⚠ الثغرة التي أغلقها — تحويلٌ مفتوح مؤكَّد بالاختبار ─────────────
 * `LoginForm` و`SignupForm` يقرآن `?next=` من العنوان — وهو مدخلٌ
 * يتحكّم فيه من صنع الرابط — ويمرّرانه إلى `signIn({ redirectTo })`.
 * و`Auth.js` يمنع العنوان المطلق المخالف للأصل، لكنه **لا يمنع
 * المسار المزدوج**: `//evil.com` يبدأ بشرطة فيُعدّ نسبيًّا، ثم يقرؤه
 * المتصفّح عنوانًا كامل البروتوكول.
 *
 * مقيسٌ على البناء نفسه بتسجيل دخولٍ حقيقيّ:
 *
 *   next=https://example.com/evil  →  بقي داخل الموقع        ✓
 *   next=//example.com/evil        →  https://example.com/evil  ⚠
 *
 * وأثرُه تصيُّدٌ مقنع: الرابط الذي تراه الضحية نطاقُ المنصّة الحقيقي،
 * وتُدخل بياناتها فيه فعلًا، ثم تُقذف إلى موقع المهاجم **بعد نجاح
 * الدخول** — فيبدو ما يليه امتدادًا للجلسة التي بدأتها للتوّ.
 *
 * ── القاعدة ─────────────────────────────────────────────────────────
 * يُقبل **مسارٌ داخليّ واحد** لا غير: يبدأ بشرطة مائلة واحدة، ولا
 * تليها شرطةٌ ثانية، ولا يحوي شرطةً خلفية ولا محرف تحكّم. المتصفّحات
 * تعامل `/\` معاملة `//`، فمُنع الاثنان.
 *
 * وما خالف ذلك يسقط إلى الوجهة الافتراضية **بصمت**: المستخدم لم يطلب
 * شيئًا ليُخبَر برفضه، والرسالة هنا تفيد صانع الرابط لا صاحبَ الحساب.
 *
 * ── ولماذا على الخادم لا في النموذج ─────────────────────────────────
 * النموذج ليس حدًّا أمنيًّا. الإجراء الخادميّ نقطةُ HTTP عامّة يبلغها
 * طلبٌ مصنوع بأي قيمة، فالتطهير يقع حيث تُستهلك القيمة.
 */
export function safeNextPath(
  value: string | undefined | null,
): string | undefined {
  if (!value || value.length > 512) return undefined;

  /* محرف تحكّم أو شرطة خلفية في أي موضع */
  if (/[\u0000-\u001f\\]/.test(value)) return undefined;

  /* شرطة واحدة في البداية، ولا شرطة ثانية بعدها */
  if (!/^\/(?!\/)/.test(value)) return undefined;

  return value;
}
