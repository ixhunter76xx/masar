/**
 * عرض الأسعار.
 *
 * الدينار البحريني ثلاث خانات عشرية (١ د.ب = ١٠٠٠ فلس)، والقاعدة تخزّن
 * الفلس عددًا صحيحًا. التحويل هنا في موضع واحد فلا يتكرّر بقسمة يدوية
 * في كل صفحة — وأي خطأ فيه يظهر في كل مكان دفعةً واحدة لا في مكان واحد.
 */
export const FILS_PER_DINAR = 1000;

/**
 * العملة مثبَّتة على الدينار البحريني — عمدًا وصراحةً.
 *
 * ── لماذا التثبيت بدل «الدعم» ───────────────────────────────────────
 * `Product.currency` و`Order.currency` موجودان في المخطط ويُقرآن،
 * لكن كل موضع عرض يكتب «د.ب» يدويًا، وهذه الدالة تقسم على ألف وتثبّت
 * ثلاث خانات — وكلاهما خاصّ بالدينار البحريني. أي منتج بعملة أخرى
 * كان سيُعرض دينارًا بحرينيًا، وبعملة ذات خانتين سيكون **أبعد بعشرة
 * أضعاف**. أي أن المخطط كان يَعِد بما لا تستطيع الواجهة قوله — وهو
 * أسوأ من عدم النمذجة، لأنه يدعو إلى الخطأ بدل أن يمنعه.
 *
 * ── ولماذا لا يُحذف الحقل ───────────────────────────────────────────
 * حذفه هجرة تُفقد بيانات، وإعادته لاحقًا هجرة أخرى. تركُه مع تثبيت
 * صريح هنا يجعل إضافة عملة ثانية يومًا **تغييرًا في هذا الملف وحده**
 * وفي مواضع العرض التي تشير إليه، لا في المخطط.
 *
 * إن أُضيفت عملة ثانية: هذه الدالة تستقبل رمز العملة، وتُقرأ خاناتها
 * العشرية منه، ويستبدل كل «د.ب» مكتوبة يدويًا باسم مشتقّ.
 */
export const CURRENCY = {
  code: "BHD",
  /** ما يُكتب بجانب الرقم في الواجهة */
  label: "د.ب",
  /** الدينار البحريني ثلاث خانات عشرية — ليس افتراضًا عامًّا */
  decimals: 3,
} as const;

export function formatFils(fils: number): string {
  return (fils / FILS_PER_DINAR).toFixed(CURRENCY.decimals);
}

/** أرخص سعر في مجموعة — لعبارة «يبدأ من» */
export function lowestPrice(prices: number[]): number | null {
  return prices.length ? Math.min(...prices) : null;
}

/** مجموع أسعار المنتجات الفردية مطروحًا منه سعر الحزمة */
export function bundleSaving(bundleFils: number, partsFils: number[]): number {
  const parts = partsFils.reduce((sum, value) => sum + value, 0);
  return Math.max(0, parts - bundleFils);
}
