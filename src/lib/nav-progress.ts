/**
 * عدّاد التنقّلات الجارية — مخزنٌ خارجيّ صغير خارج React.
 *
 * ── لماذا مخزنٌ خارجيّ لا سياق ───────────────────────────────────────
 * `useLinkStatus` لا يُقرأ إلا من **داخل** `<Link>`، فحالة الانتظار
 * تولد موزّعةً على عشرات الروابط. والشريط العلويّ واحد. فالحاجة أن
 * يعلن كل رابطٍ عن نفسه في مكانٍ واحد يقرأه الشريط.
 *
 * والسياق كان يعني إعادة تصيير كل رابطٍ تحت المزوّد كلّما بدأت تنقّلة
 * أو انتهت. المخزن الخارجيّ يُخطر مشتركيه وحدهم — والمشترك واحد.
 *
 * ── لماذا عدّاد لا راية ─────────────────────────────────────────────
 * قد يبدأ رابطان معًا: ينقر المستخدم رابطًا ثم يبدّل رأيه فينقر آخر
 * قبل وصول الأول. الراية تُطفأ بأول انتهاء فيختفي الشريط والتنقّلة
 * الثانية ما زالت جارية. العدّاد لا يبلغ الصفر إلا بانتهاء الجميع.
 *
 * ولا يُسمح له بالنزول تحت الصفر: تفكيك رابطٍ وهو منتظِر (وهو ما يحدث
 * دائمًا — الصفحة القديمة تُفكَّك) يستدعي `navEnd` مرّة واحدة لكل
 * `navBegin`، لكن الحارس يبقى لأن خطأً واحدًا في الترتيب يترك العدّاد
 * سالبًا فلا يظهر الشريط بعدها أبدًا.
 */

let running = 0;
const listeners = new Set<() => void>();

function emit() {
  for (const listener of listeners) listener();
}

export function navBegin() {
  running += 1;
  emit();
}

export function navEnd() {
  running = Math.max(0, running - 1);
  emit();
}

export function subscribeNav(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function getNavSnapshot() {
  return running;
}

/** على الخادم لا تنقّل جارٍ — وقيمةٌ ثابتة تمنع اختلاف الترطيب */
export function getNavServerSnapshot() {
  return 0;
}
