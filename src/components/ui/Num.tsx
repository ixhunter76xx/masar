import { ar } from "@/lib/numerals";
import { cn } from "@/lib/utils";

/**
 * عددٌ في نصّ عربي — معرَّبٌ ومعزولٌ اتجاهيًّا.
 *
 * ── لماذا مكوّن لا صنف ──────────────────────────────────────────────
 * الصنف `.numeric` يضبط الخطّ والاتجاه ولا يستطيع تحويل الرسوم:
 * لا تملك CSS تعريب الأرقام. فبقيت الأعداد لاتينية في نصّ عربيّ رغم
 * أن التصميم المعتمد يعرضها عربية-هندية. هذا المكوّن يجمع الأمرين
 * في موضع واحد، فلا يُنسى التعريب في الموضع الثاني والخمسين.
 *
 * ── ⚠ ومتى لا يُستعمل ───────────────────────────────────────────────
 * المعرّفات تبقى لاتينية وتأخذ `.code`: رمز المقرر (ARAB110)، ورقم
 * الطلب (MSR-2026-0001)، والهاتف، واسم المستخدم، وبصمة الخطأ. هذه
 * تُملى وتُنسخ وتُطابق حرفيًّا، وتعريبها يجعلها غير قابلة لذلك.
 */
export function Num({
  children,
  className,
}: {
  children: string | number;
  className?: string;
}) {
  return <span className={cn("numeric", className)}>{ar(children)}</span>;
}

/**
 * عددٌ مع تمييزه الصحيح: «٥ دروس» / «١٢ درسًا».
 *
 * العربية تميّز من ٣ إلى ١٠ بجمعٍ، ومن ١١ فصاعدًا بمفردٍ منصوب.
 * و«١٢ دروس» خطأ نحويّ كان معروضًا فعلًا على صفحة المقرر.
 */
export function Counted({
  n,
  few,
  many,
  className,
}: {
  n: number;
  few: string;
  many: string;
  className?: string;
}) {
  return (
    <>
      <Num className={className}>{n}</Num> {n >= 3 && n <= 10 ? few : many}
    </>
  );
}
