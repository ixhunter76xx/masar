"use client";

import * as React from "react";
import Link from "next/link";

import { LinkPending } from "@/components/motion/LinkPending";

/**
 * ══ رابطٌ يعترف بالنقرة ═══════════════════════════════════════════
 *
 * بديلٌ مطابقٌ لـ`next/link` في كل خصائصه، يضيف شيئًا واحدًا: يعلن
 * انتظاره. يُستورَد باسم `Link` فلا يتغيّر شيءٌ في مواضع الاستعمال:
 *
 *   import { NavLink as Link } from "@/components/ui/NavLink";
 *
 * ── لماذا غلافٌ لا تعديلٌ في كل موضع ────────────────────────────────
 * الروابط الملاحية في المنصّة نحو الأربعين، في عشرين ملفًّا، بأصنافٍ
 * وبِنى مختلفة. ووضعُ `LinkPending` في كلٍّ منها يدويًا يعني أربعين
 * فرصةً للنسيان، وأربعين موضعًا يجب تذكّرها عند أي رابطٍ جديد. سطر
 * استيرادٍ واحد لكل ملفّ يجعل القاعدة **بنيويّة**: كل رابطٍ في الملفّ
 * يعترف بالنقرة، بما فيه ما يُضاف غدًا.
 *
 * ── ولماذا لا يُصيَّر غلافٌ حول الأبناء ──────────────────────────────
 * الأبناء يُمرَّرون كما هم إلى `next/link`. فالبِنى القائمة — شبكة،
 * `flex` بفجوات، `truncate`, `absolute inset-0` — لا يتغيّر منها شيء.
 * المضاف عقدةٌ واحدة `sr-only` وهي مطلقةُ الموضع، خارج التدفّق تمامًا.
 *
 * ── الأثر على الحزمة ────────────────────────────────────────────────
 * الوسم `<a>` يصير عميلًا، لكن **محتواه يبقى خادميًّا**: يُمرَّر شقًّا
 * (slot) لا يُعاد تصييره على العميل. والمكوّن نفسه ملفٌّ واحد مشترك،
 * فالزيادة الحقيقية سطورٌ لا نسخة لكل موضع.
 */
export function NavLink({
  children,
  pendingLabel,
  ...props
}: React.ComponentProps<typeof Link> & {
  /** ما يُعلنه القارئ الصوتي أثناء الانتظار */
  pendingLabel?: string;
}) {
  return (
    <Link {...props}>
      <LinkPending label={pendingLabel} />
      {children}
    </Link>
  );
}
