"use client";

import * as React from "react";
import { useLinkStatus } from "next/link";

import { navBegin, navEnd } from "@/lib/nav-progress";

/**
 * ══ إعلان النقرة ═══════════════════════════════════════════════════
 *
 * يُركَّب **داخل** `<Link>` فيقرأ حالة انتظاره ويعلنها في موضعين:
 * سمة `data-pending` على الرابط نفسه (يلتقطها CSS)، وعدّاد التنقّلات
 * الذي يقود الشريط العلويّ.
 *
 * ── العلّة التي وُجد لها ─────────────────────────────────────────────
 * صفحات المنطقة المحمية تُبنى على الخادم بقراءةٍ من قاعدةٍ في
 * `us-east-2`، والمستخدم في البحرين. المقيس في `PORT-HANDOFF.md`:
 * `/profile` ‏١٠٠١ms و`/messages` ‏١٤٥٠ms. وفي تلك الفترة كان
 * `AreaSwitch` وحده يعلن أن النقرة وصلت؛ أمّا الشريط الجانبي
 * وتبويبات المقرر وبطاقات الكتالوج فلا شيء فيها يتغيّر.
 *
 * وثانيةٌ ونصف بلا أثرٍ للنقرة تُقرأ «الزرّ لا يعمل» — فيُنقر ثانيةً.
 *
 * ── لماذا السمة لا صنفٌ على الابن ────────────────────────────────────
 * الروابط هنا مكتوبةٌ بأصنافٍ مختلفة في عشرين ملفًّا، ولفّ محتواها في
 * غلافٍ جديد كان يكسر تخطيطها (شبكة، `flex` بفجوات، `truncate`).
 * والسمة على الوسم نفسه لا تضيف عقدةً ولا تغيّر تخطيطًا، وتُعالَج
 * بقاعدة CSS واحدة — فالمظهر واحدٌ في كل موضع بلا أن يعرف كلّ رابطٍ
 * شيئًا عن ذلك.
 *
 * ── ولماذا لا يُصيَّر شيءٌ مرئيّ ──────────────────────────────────────
 * المرئيّ كلّه في CSS والشريط العلويّ. ما يُصيَّر هنا إعلانٌ للقارئ
 * الصوتيّ وحده، بـ`sr-only` أي `position:absolute` — فهو خارج التدفّق
 * ولا يستهلك فجوة `flex` ولا يزيح شيئًا.
 * ═══════════════════════════════════════════════════════════════════
 */
export function LinkPending({ label = "جارٍ الفتح…" }: { label?: string }) {
  const { pending } = useLinkStatus();
  const markerRef = React.useRef<HTMLSpanElement>(null);

  React.useEffect(() => {
    if (!pending) return;

    /* المرساة تُقرأ داخل التأثير لا في التصيير: عند أول تصيير لا يكون
       العنصر في الشجرة بعد. */
    const anchor = markerRef.current?.closest("a");
    anchor?.setAttribute("data-pending", "");
    navBegin();

    return () => {
      anchor?.removeAttribute("data-pending");
      navEnd();
    };
  }, [pending]);

  return (
    <span ref={markerRef} className="sr-only">
      {pending ? label : null}
    </span>
  );
}
