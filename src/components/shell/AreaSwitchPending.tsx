"use client";

import { useLinkStatus } from "next/link";

/**
 * إشعارٌ فوريّ بأن النقرة وصلت.
 *
 * ── العلّة التي وُجد لها ─────────────────────────────────────────────
 * الانتقال من الكتالوج إلى الدراسة يعبر من تخطيط `(public)` إلى
 * `(app)`، و`(app)/layout.tsx` ينتظر `getShellData()` — أي رحلة إلى
 * قاعدة البيانات. و`loading.tsx` يعيش **داخل** ذلك التخطيط، فلا يُرسم
 * قبل أن يُحلّ التخطيط نفسه.
 *
 * والنتيجة مقيسة على الإنتاج: **٥٩٠ مللي ثانية لا يتغيّر فيها شيء على
 * الشاشة** — لا هيكل ولا مؤشّر ولا أثر للنقرة. وعلى بيانات الهاتف تصير
 * ثوانيَ. فيقرأها المستخدم «الزرّ لا يعمل» ويضغط ثانيةً وثالثة.
 *
 * `useLinkStatus` يعطي حالة الانتظار من `Link` نفسه، فتُعلَن النقرة في
 * الإطار التالي لها لا بعد وصول البيانات.
 *
 * ── ولماذا شفافية لا دوّارة ─────────────────────────────────────────
 * الشكل الأساسيّ لا يتغيّر: لا عنصر جديد يظهر ولا يتبدّل مقاس. الحبّة
 * المضغوطة تخفت قليلًا وحدها، وهو ما يكفي ليعرف الإصبع أنه سُمِع.
 * ولأن التغيير شفافية بحتة فهو ينجو من `prefers-reduced-motion`
 * الذي يُبقي الشفافية ويُسقط الحركة المكانيّة.
 */
export function AreaSwitchLabel({ label }: { label: string }) {
  const { pending } = useLinkStatus();

  return (
    <span
      className={
        pending
          ? "opacity-55 transition-opacity duration-150"
          : "transition-opacity duration-150"
      }
    >
      {label}
      {/* يُعلَن للقارئ الصوتي دون أن يشغل حيّزًا يزحزح الحبّة */}
      {pending && <span className="sr-only"> — جارٍ الفتح…</span>}
    </span>
  );
}
