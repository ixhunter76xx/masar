"use client";

import { LinkPending } from "@/components/motion/LinkPending";

/**
 * إشعارٌ فوريّ بأن النقرة وصلت — في حبّة المبدّل.
 *
 * ── العلّة التي وُجد لها ─────────────────────────────────────────────
 * الانتقال من الكتالوج إلى الدراسة يعبر من تخطيط `(public)` إلى
 * `(app)`، و`(app)/layout.tsx` ينتظر `getShellData()` — أي رحلة إلى
 * قاعدة البيانات. و`loading.tsx` يعيش **داخل** ذلك التخطيط، فلا يُرسم
 * قبل أن يُحلّ التخطيط نفسه.
 *
 * والنتيجة مقيسة على الإنتاج: **٥٩٠ مللي ثانية لا يتغيّر فيها شيء على
 * الشاشة** — لا هيكل ولا مؤشّر ولا أثر للنقرة. وعلى بيانات الهاتف تصير
 * ثوانيَ. فيقرأها المستخدم «الزرّ لا يعمل» ويضغط ثانيةً وثالثة.
 *
 * ── ⚠ ما تغيّر هنا: صار الإعلان عامًّا لا خاصًّا بهذه الحبّة ─────────
 * كان هذا الملفّ يقرأ `useLinkStatus` بنفسه ويخفت النصّ بيده. وكان
 * ذلك صحيحًا يوم كان **الموضع الوحيد** في المنصّة الذي يعترف بالنقرة.
 * ثم صار كل رابطٍ يعترف بها عبر `LinkPending` وقاعدةٍ واحدة في
 * `globals.css`. فبقاء نسخةٍ يدوية هنا يعني لسانين لمعنًى واحد،
 * ويعني أن هذا الرابط وحده **لا يُغذّي شريط التقدّم** العلويّ.
 *
 * والنتيجة البصرية لم تتغيّر: خفوتٌ لطيف بلا دوّارة، ولا عنصر جديد
 * يظهر، ولا مقاس يتبدّل — وهو ما كانت تفعله النسخة القديمة بالضبط.
 * والشفافية وحدها تنجو من `prefers-reduced-motion` الذي يُبقيها
 * ويُسقط الحركة المكانيّة.
 */
export function AreaSwitchLabel({ label }: { label: string }) {
  return (
    <>
      <LinkPending label={`جارٍ فتح ${label}…`} />
      {label}
    </>
  );
}
