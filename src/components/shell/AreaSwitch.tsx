import Link from "next/link";

import { cn } from "@/lib/utils";

/**
 * مبدّل المنطقتين — الكتالوج والدراسة.
 *
 * ── لماذا يوجد ──────────────────────────────────────────────────────
 * للمنصّة منطقتان: كتالوجٌ عامّ يُتصفَّح ويُشترى منه، ومنطقة دراسة
 * خاصّة. وعناصر التنقّل الستة كلها داخل الثانية، فلم يكن للداخل بابٌ
 * ظاهرٌ يعود منه. والنمط قياسيّ في أسواق المقررات: بابُ التصفّح وبابُ
 * ما اشتريتَ ظاهران معًا.
 *
 * ── ولماذا مبدّل لا رابط ────────────────────────────────────────────
 * الرابط الواحد يقول «اذهب إلى هناك». والمبدّل يقول «هاتان منطقتان،
 * وأنت في هذه» — فيُظهر البنية لا الوجهة وحدها، ويستقرّ موضعُ الباب
 * بدل أن يتبدّل مسمّاه بحسب مكانك.
 *
 * ── الأسماء ─────────────────────────────────────────────────────────
 * «الكتالوج» هي كلمة الرأسية العامّة نفسها للمكان ذاته، فالمكان الواحد
 * يحمل اسمًا واحدًا في كل موضع. و«الدراسة» تصف الجانب الخاصّ كلَّه
 * (لوحة، مقررات، درجات، رسائل) بلا أن تصطدم بـ«مقرراتي» — وهي وجهةٌ
 * واحدة داخله لا اسمٌ للمنطقة.
 *
 * ── ⚠ الموضع، وهو أهمّ ما في هذا الملف ──────────────────────────────
 * ثابتٌ بالنسبة **للنافذة**، ومركّبٌ خارج الرأسيتين.
 *
 * مرصوفًا بين إخوته كان يزيح موضعه كلّما اختلف ما حوله: زرّ قائمة في
 * جهة وشعارٌ في أخرى، وعنوانٌ يظهر ويختفي، ورأسيةُ الحساب تبدأ بعد
 * ٢٦٠px من الشريط الجانبي بينما العامّة تبدأ من الحافّة. فيقفز بين
 * السياقين — وهو أسوأ ما يفعله عنصرٌ وظيفتُه أن يكون المرجع الثابت.
 *
 * ولا يُركَّب داخل رأسية: كلتاهما تحمل `backdrop-blur`، وأيّ مرشِّح
 * يجعل العنصر الأب **كتلةَ احتواء** لكل `position:fixed` بداخله —
 * فيصير «ثابتًا بالنسبة للنافذة» اسمًا وثابتًا بالنسبة للرأسية فعلًا.
 * (`.ambient` آمن: `relative` و`isolation` فقط، بلا مرشِّح.)
 *
 * وخصائص فيزيائية (`left-1/2` + `-translate-x-1/2`) لا منطقية: المنتصف
 * لا اتجاه له، و`start-1/2` ينقلب معناه بين RTL وLTR فيحتاج إشارة
 * مختلفة لكلٍّ منهما. هذا الاستثناء الوحيد لقاعدة تفضيل المنطقيّ.
 */
export function AreaSwitch({ current }: { current: "catalogue" | "study" }) {
  const areas = [
    { key: "catalogue", label: "الكتالوج", href: "/courses" },
    /* `/dashboard` لا `/learn`: هو صدر المنطقة وأول عناصر التنقّل،
       ومنه يُتفرَّع. وللزائر المجهول يحوّله الحارس إلى الدخول ثم يعيده
       — وهو السلوك المطلوب لا عيبٌ فيه. */
    { key: "study", label: "الدراسة", href: "/dashboard" },
  ] as const;

  return (
    <nav
      aria-label="منطقة الموقع"
      className="fixed top-3 left-1/2 z-50 -translate-x-1/2
        flex gap-0.5 rounded-full border border-line-soft bg-[var(--sunk)] p-[3px]
        shadow-[0_6px_20px_-12px_var(--shadow-lift)] backdrop-blur-md"
    >
      {areas.map((area) => {
        const isHere = area.key === current;
        return (
          <Link
            key={area.key}
            href={area.href}
            aria-current={isHere ? "page" : undefined}
            className={cn(
              "press inline-flex items-center rounded-full whitespace-nowrap",
              /* المقاسات من المعاينة حرفيًّا: ‎.78rem/‎.4rem ‎.85rem،
                 وتصغيرٌ تحت ٦٢٠px إلى ‎.73rem/‎.4rem ‎.6rem — وهو علاج
                 المعاينة للضيق: يتقلّص المبدّل، لا يُختصر ما حوله. */
              "py-1.5 text-[0.73rem] px-2.5 sm:px-3.5 sm:text-[0.78rem]",
              "font-medium transition-colors",
              isHere
                ? "bg-panel-high font-semibold text-paper"
                : "text-subtle hover:text-paper",
            )}
          >
            {area.label}
          </Link>
        );
      })}
    </nav>
  );
}
