import { Logo } from "@/components/ui/Logo";
import { SITE } from "@/lib/site";

/**
 * ══ شاشة إقلاع التطبيق المثبَّت ═════════════════════════════════════
 *
 * تظهر حين يُفتح «مسار» من أيقونته على الشاشة الرئيسية، لا حين يُزار
 * في المتصفّح. تسدّ الفجوة بين شاشة النظام الساكنة — التي يرسمها
 * أندرويد/iOS من البيان — وأوّل إطارٍ يرسمه التطبيق، وهي فجوةٌ تُقاس
 * بأجزاءٍ من الثانية على شبكةٍ جيّدة وبثوانٍ على شبكةٍ رديئة، وكانت
 * تُملأ بلونٍ مصمتٍ ساكن.
 *
 * ── لماذا CSS وحدها بلا JS ──────────────────────────────────────────
 * الكشف بجافاسكربت (`matchMedia` أو `navigator.standalone`) لا يقع إلا
 * بعد ترطيب الصفحة، فيومض محتوى التطبيق قبل أن تُركَّب الشاشة فوقه —
 * أي أن العلاج يُحدث العيب الذي وُجد لعلاجه. و`@media (display-mode:
 * standalone)` يُقيَّم مع أوّل رسمٍ للصفحة، فالشاشة موجودةٌ في الإطار
 * الأول. ولذلك هذا مكوّن خادم: لا حالة، ولا مستمع، ولا كيلوبايت واحد
 * من JS.
 *
 * ── ولماذا لا تحجب النقر أبدًا ──────────────────────────────────────
 * `pointer-events: none` مفروضةٌ طوال عمرها. الشاشة زخرفةٌ فوق تطبيقٍ
 * جاهز، فلو تأخّر إخفاؤها لسببٍ ما بقي التطبيق مستعملًا تحتها. زخرفةٌ
 * تمنع الاستعمال عطلٌ لا أثرٌ جانبيّ.
 *
 * ── وحكاية الحركة من الشعار نفسه ────────────────────────────────────
 * الهوية طريقٌ يمشي عليه خرّيج. فالحركة تعيد رسم المعنى لا تزيّنه:
 * الشعار يستقرّ صاعدًا، ثم يُمدّ تحته خيطُ الطريق من **بداية السطر**
 * — يمينًا في العربية — فيقرأ كمسارٍ يُقطع لا كخطٍّ يُرسم.
 *
 * ⚠ الاتجاه هنا ليس تفصيلًا: `transform-origin` لا يقبل الكلمات
 * المنطقية (`inline-start` تسقط إلى المركز صامتةً، وقد وقعت في هذا
 * المستودع من قبل)، فالقاعدة مشروطةٌ بـ`[dir]` في `globals.css`.
 * ═══════════════════════════════════════════════════════════════════
 */
export function PwaLaunch() {
  return (
    <div className="pwa-launch" aria-hidden="true" role="presentation">
      <div className="pwa-launch__stack">
        <div className="pwa-launch__mark">
          <Logo size={104} variant="full" bare />
        </div>
        <span className="pwa-launch__road" />
        <span className="pwa-launch__word">{SITE.tagline}</span>
      </div>
    </div>
  );
}
