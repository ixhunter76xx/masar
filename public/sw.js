/**
 * عامل الخدمة.
 *
 * ── لماذا هو موجود أصلًا ────────────────────────────────────────────
 * كروم على أندرويد لا يعرض "تثبيت التطبيق" إلا لموقع يملك بيانًا صالحًا
 * **وعامل خدمة يعالج حدث fetch**. بدونه يبقى الخيار "إضافة اختصار" لا
 * تثبيتًا حقيقيًا: يفتح في تبويب متصفح لا في نافذة مستقلة.
 *
 * ── ولماذا لا يخزّن شيئًا ───────────────────────────────────────────
 * المنصة كلها خلف تسجيل دخول، وصفحاتها تُصيَّر على الخادم لكل مستخدم
 * بدوره وبياناته. تخزين استجابة درجات طالب أو محادثته الخاصة في ذاكرة
 * المتصفح يعني أن يراها من يفتح الجهاز بعده، أو أن يرى المستخدم بيانات
 * حسابه السابق بعد تسجيل الخروج.
 *
 * فالعامل يمرّر كل شيء إلى الشبكة بلا تخزين. القيمة هي التثبيت لا
 * العمل دون اتصال — وهذه مقايضة واعية: أي تخزين هنا يحتاج تصميم إبطال
 * مرتبطًا بالجلسة، وهو عمل قائم بذاته لا يُضاف عرضًا.
 * ────────────────────────────────────────────────────────────────────
 */

self.addEventListener("install", () => {
  // لا تنتظر إغلاق التبويبات القديمة
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      // نظّف أي ذاكرة خبّأتها نسخة سابقة من هذا الملف
      const names = await caches.keys();
      await Promise.all(names.map((name) => caches.delete(name)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  // المرور إلى الشبكة صراحةً — وجود المعالج هو شرط قابلية التثبيت
  event.respondWith(fetch(event.request));
});
